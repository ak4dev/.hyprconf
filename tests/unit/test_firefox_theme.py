def test_rendered_mode_is_what_the_stylesheet_declares() -> None:
    """The template carries `--hyprconf-theme-mode: {{ mode }}` — Omarchy's
    own resolution (mode key, theme_type, legacy light.mode, luminance) — so
    the mode is read back from the rendered file, never re-derived here."""
    assert ft.rendered_mode(CSS_DARK) == "dark"
    assert ft.rendered_mode(CSS_LIGHT) == "light"
    assert ft.rendered_mode(b":root {\n  --hyprconf-theme-mode:light ;\n}\n") == "light"
    # A stylesheet with no declaration (a user's own template) is treated as dark.
    assert ft.rendered_mode(b":root { --toolbar-bgcolor: #000; }\n") == "dark"
    assert ft.rendered_mode(b"\xff\xfe not utf-8") == "dark"


def test_theme_prefs_follow_the_mode() -> None:
    dark = ft.theme_prefs("dark")
    light = ft.theme_prefs("light")
    assert dark["toolkit.legacyUserProfileCustomizations.stylesheets"] is True
    # activeThemeID forces the light/dark colour scheme — on FF 154 the
    # built-in ids are inApp, so it never unlocks the --lwt-* block; the
    # template's direct selectors paint (firefox_theme.py's THEME_ID note).
    assert dark["extensions.activeThemeID"] == "firefox-compact-dark@mozilla.org"
    assert light["extensions.activeThemeID"] == "firefox-compact-light@mozilla.org"
    assert dark["ui.systemUsesDarkTheme"] == 1 and light["ui.systemUsesDarkTheme"] == 0
    # browser.theme.{content,toolbar}-theme are what Firefox writes from the
    # active theme, not inputs — exactly three prefs are managed.
    assert (
        set(dark)
        == set(light)
        == {
            "toolkit.legacyUserProfileCustomizations.stylesheets",
            "extensions.activeThemeID",
            "ui.systemUsesDarkTheme",
        }
    )


