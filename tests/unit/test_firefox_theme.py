"""Tests for hyprconf.firefox_theme — Omarchy's rendered userChrome.css into profiles.

Omarchy ships no Firefox theming (omarchy-theme-set-browser is Chromium-only).
The overlay's bridge is a user template, themed/userChrome.css.tpl, which
Omarchy's own omarchy-theme-set-templates renders into
~/.local/state/omarchy/current/theme/userChrome.css on every theme set. This
module must: find the right profiles the way Firefox does (every [Install…]
Default — each build honours only its own section — falling back to a Profile
Default=1, then the first profile), copy that rendered file byte-for-byte into
each profile, merge — never clobber — the profile's user.js with prefs that
follow the mode the file declares, never render anything itself (a missing
render is an error naming `omarchy theme refresh`, the command that renders
the current theme's templates), and be idempotent, since the hook re-runs on
every theme switch and every install.sh run.

Hermetic: HOME relocated, PATH pinned to a fake-bins dir plus /usr/bin,
notify() replaced. In-process, notify() is the module's only subprocess at
all; the hook test below runs as a real bash subprocess and stubs Omarchy's
theme commands there, where it can prove none of them ran.
"""

